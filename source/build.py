import os
import re
import sys

ROOT = os.path.dirname(os.path.abspath(__file__))
os.chdir(ROOT)
sys.path.insert(0, ROOT)
import weasyprint  # noqa: E402
if not weasyprint.__version__.startswith("70."):
    sys.exit(f"This book is laid out for WeasyPrint 70 (found {weasyprint.__version__}). pip install weasyprint==70.0")
import content as C  # noqa: E402


def chips(s):
    s = re.sub(r"\[\[@([^\]]+)\]\]", r'<span class="knob">\1</span>', s)
    s = re.sub(r"\[\[~([^\]]+)\]\]", r'<span class="scr">\1</span>', s)
    s = re.sub(r"\[\[([^\]]+)\]\]", r'<span class="btn">\1</span>', s)
    return s.replace("OCT-", "OCT&#8722;")


import figures as F  # noqa: E402

CONTROLS = {"MASTER", "SELECT", "PRESETS", "ALGORITHM", "KNOB 1", "KNOB 2", "KNOB 3", "KNOB 4", "OCT-", "OCT+",
            "FX", "SCL", "ENV", "LFO", "EDIT", "GLO", "HOME", "SAVE", "ARP", "SEQ", "PLAY", "REC"}
SCREENS = {
    "stage": F.scr_stage,
    "browser": lambda: F.scr_knobs("PRESETS", [("LIST", "ALL"), ("SOUND", .5), ("FAV", "ON"), ("ENGINE", "SID")]),
    "scales": lambda: F.scr_knobs("SCALES", [("FAMILY", "ALL"), ("SCALE", "MIN"), ("ROOT", "A"), ("QNT", "SNAP")]),
    "chord": lambda: F.scr_knobs("CHORD", [("CHRD", "AUTO"), ("VOIC", "OPEN"), ("STRUM", "1/32"), ("STROKE", "DOWN")]),
    "grid": F.scr_grid,
    "ampenv": lambda: F.scr_knobs("AMP ENV", [("ATK", .75), ("DEC", .4), ("SUS", .6), ("REL", .7)]),
    "reverb": lambda: F.scr_knobs("REVERB", [("MIX", 1.0), ("SIZE", .6), ("DAMP", .4), ("TONE", .5)]),
    "song": F.scr_song,
}
KEYS_RE = re.compile(r"\b(white keys?|black keys?|keys?)\b")   # lower case only: not the KEY screen


def lesson_panel(section):
    """Light every control the numbered steps use; badge each with the first step that uses it."""
    first = {}
    for ol in re.finditer(r'<ol class="steps" style="counter-reset: s (\d+)">(.*?)</ol>', section, re.S):
        n = int(ol.group(1))
        for li in re.findall(r"<li>(.*?)</li>", ol.group(2), re.S):
            n += 1
            for c in re.findall(r"\[\[@?([A-Z0-9 +\-]+)\]\]", li):
                if c in CONTROLS:
                    first.setdefault(c, n)
            plain = re.sub(r"\[\[.*?\]\]", "", li).replace("play any keys", "")   # "Don't play any keys"
            if KEYS_RE.search(plain):
                first.setdefault("KEYS", n)
    return first


def fill_panels(section):
    m = re.search(r"<!--PANEL:(\w*)-->", section)
    if not m:
        return section
    first = lesson_panel(section)
    scr = SCREENS[m.group(1)]() if m.group(1) else None
    nums = {k: str(v) for k, v in first.items()}
    svg = F.fm1_panel(hl=[k for k in first if k != "KEYS"], keys_hl="KEYS" in first, nums=nums, screen=scr)
    cap = ("Today's controls are lit. Each pink number is the first step that uses that control. "
           "The screen is a simplified example of the page, not a screenshot.")
    PANEL_LOG.append((re.search(r'id="(\w+)"', section).group(1), dict(sorted(first.items(), key=lambda kv: kv[1]))))
    return section.replace(m.group(0), f'<figure class="panelfig">{svg}<figcaption>{cap}</figcaption></figure>')


PANEL_LOG = []
body = "".join(chips(fill_panels(x)) for x in C.BOOK)
with open("docs/PANEL-NUMBERS.md", "w") as fh:
    fh.write("# Panel numbers (generated by build.py)\n\nEach lesson's panel badges, computed from its numbered steps.\n\n")
    for sid, first in PANEL_LOG:
        fh.write(f"- **{sid}**: " + ", ".join(f"{k} {v}" for k, v in first.items()) + "\n")
html = f"""<!doctype html><html lang="en-AU"><head><meta charset="utf-8"><title>Melodee, Gently</title>
<meta name="author" content="slowphase"><meta name="description" content="A beginner's guide to Melodee {C.FW} on the M-VAVE FM-1">
<link rel="stylesheet" href="style.css"></head><body>{body}</body></html>"""
open("book.html", "w").write(html)
out = sys.argv[1] if len(sys.argv) > 1 else "Melodee-Gently.pdf"
doc = weasyprint.HTML(string=html, base_url=ROOT).render()
print("pages:", len(doc.pages))
doc.write_pdf(out)
